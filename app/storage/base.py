"""The blob-store interface. Local disk implements it today; an S3 adapter can implement it
later without touching callers.

Keys are `/`-separated paths such as `<workspace>/<collection>/<document>/original`. Every
segment is generated by the server (UUIDs and fixed names), never taken from user input, and
implementations must still reject anything else so a bug can never become a path traversal.
"""

from __future__ import annotations

import re
from typing import Protocol, runtime_checkable

_SEGMENT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")


class BlobNotFound(Exception):
    """The requested key does not exist."""


class InvalidKey(ValueError):
    """The key is malformed (empty, absolute, `..`, odd characters)."""


def split_key(key: str) -> list[str]:
    """Validate a key or prefix and return its segments."""
    if not key or key.startswith("/") or key.endswith("/"):
        raise InvalidKey(f"invalid key: {key!r}")
    parts = key.split("/")
    if any(p in {".", ".."} or not _SEGMENT.match(p) for p in parts):
        raise InvalidKey(f"invalid key: {key!r}")
    return parts


@runtime_checkable
class BlobStore(Protocol):
    async def put(self, key: str, data: bytes) -> None:
        """Create or atomically replace a blob."""

    async def get(self, key: str) -> bytes:
        """Return the blob, or raise `BlobNotFound`."""

    async def exists(self, key: str) -> bool: ...

    async def delete(self, key: str) -> None:
        """Delete a blob. Deleting a missing key is not an error."""

    async def delete_prefix(self, prefix: str) -> int:
        """Delete every blob under `prefix` (a folder). Returns how many were removed."""
